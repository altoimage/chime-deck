"""The shipped Material Design Icons manifest: names in, path data out.

The panel's icon picker needs two things that Home Assistant does not serve: the
list of icon names to offer, and the SVG path data to draw one. Serving the
picker from a ``.js`` bundle would put the whole set in front of a 256 MB-class
device and a webfont would add a binary and a ``@font-face`` the local UI
deliberately does not have, so this build ships the icon set as **data** instead
(2.7 MB of JSON, split into 26 shards) and serves paths on demand. That is why
``Project_state/glossary.md``'s "Home Assistant has no public icon endpoint"
matters here: we are the endpoint.

**The data.** ``data/mdi/`` holds ``index.json`` (the icon-set version, the icon
count and the shard list) and one ``{name: path}`` shard per first character of
the icon name. It is generated by ``web/scripts/generate-mdi-manifest.mjs``
(``npm run gen:icons``) from ``@mdi/svg`` **7.4.47**, the release ``@mdi/js
^7.4.47`` in ``web/package.json`` resolves to. Generation is a dev-time step
whose output is committed: end users need no Node, nothing is generated at
``pip install``, and nothing is ever written at runtime. ``@mdi/svg``'s
``meta.json`` is the source of names because ``@mdi/js``'s camelCase names cannot
be inverted (``mdiBattery10`` is ``battery-10``, not ``battery10``). A test pins
the shipped ``version`` to the ``web/package.json`` devDependency, so the manifest
cannot drift from the icons the UI bundles.

**The shards.** One 2.7 MB file would trip the repository's 500 kB committed-file
policy (``check-added-large-files``); sharding by first character keeps the
largest file at ~404 kB, and a test fails loudly if a future icon-set bump
crosses 500,000 bytes so the next person re-shards instead of committing a file
the policy rejects.

**The loader.** :func:`load_mdi_manifest` is the only reader, it reads exactly the
shards ``index.json`` lists (never a directory scan — the shipped index is the
contract), and it is lazy: importing this module does no I/O. It is the only I/O
in the ``icons`` package beyond the custom-icon ``.svg``/``.png`` existence check
in :func:`~chime_deck.icons.validate_icon_reference`.

**Broken shipped data is a bug.** :class:`MdiManifestError` is raised, never
caught: a missing or malformed manifest means the wheel is broken, and degrading
to "no icons" would hide a packaging mistake behind an empty picker.

Owning ticket: HSD-zyru.
"""

from __future__ import annotations

import json
import re
from collections.abc import Mapping
from dataclasses import dataclass
from functools import lru_cache
from importlib import resources
from importlib.resources.abc import Traversable
from types import MappingProxyType
from typing import Final, cast

__all__ = [
    "MANIFEST_INDEX_FILENAME",
    "MDI_DATA_DIRECTORY",
    "MDI_NAME_PATTERN",
    "MDI_PREFIX",
    "MDI_VIEW_BOX",
    "MdiManifest",
    "MdiManifestError",
    "icon_path",
    "load_mdi_manifest",
    "normalise_icon_name",
]

MDI_NAME_PATTERN: Final = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")
"""The only shape an MDI icon name may have, applied with ``fullmatch``.

It is also the traversal rejection: no dot, no slash, no backslash and no
uppercase can match, so a caller-supplied string cannot name a filesystem path.
It matches :data:`chime_deck.icons.resolver`'s private copy of the rule, so
the shipped manifest and a storable ``mdi:`` reference cannot disagree about what
a legal icon name is.
"""

MDI_VIEW_BOX: Final = "0 0 24 24"
"""The view box every MDI icon is drawn in.

Part of the answer, not an implementation detail: a client that only receives
``path`` data has to know the coordinate system to scale it, and MDI's is fixed
at 24 by 24 for the whole set.
"""

MDI_PREFIX: Final = "mdi:"
"""Prefix of a Home Assistant icon reference to an MDI icon (``mdi:door``)."""

MDI_DATA_DIRECTORY: Final = "mdi"
"""Name of the manifest directory inside the package's ``data/`` directory."""

MANIFEST_INDEX_FILENAME: Final = "index.json"
"""The manifest's entry point: the version, the icon count and the shard list."""

_DATA_ANCHOR: Final = "data"
"""Package-relative directory holding generated, committed data files."""

_SHARD_SEPARATORS: Final = ("/", "\\")
"""Characters a shard file name from ``index.json`` may never contain."""


class MdiManifestError(RuntimeError):
    """The icon manifest shipped inside the package is missing or malformed.

    Deliberately not caught anywhere: this is a broken wheel, not a degraded
    dependency, and every caller would have to invent the same fallback. The
    message names the offending file.
    """


@dataclass(frozen=True, slots=True)
class MdiManifest:
    """One loaded icon set: its version and the ``name -> path`` map.

    ``icons`` is a :class:`~types.MappingProxyType`, so a caller cannot corrupt
    the cached manifest for everyone else in the process.
    """

    version: str
    icons: Mapping[str, str]


def normalise_icon_name(name: str) -> str | None:
    """Return *name* as a bare MDI icon name, or ``None`` when it is not one.

    One leading :data:`MDI_PREFIX` is stripped, then the rest must match
    :data:`MDI_NAME_PATTERN` in full. Everything else — an empty string, ``..``,
    ``a/b``, an uppercase name, a name with a space, a leading slash, or a second
    ``mdi:`` — is ``None``. This is the whole traversal defence: the result is
    only ever used as a dictionary key, so a caller-supplied string can never
    become a path.

    :param name: what a client sent, either ``door`` or ``mdi:door``.
    """
    candidate = name.removeprefix(MDI_PREFIX)
    if MDI_NAME_PATTERN.fullmatch(candidate) is None:
        return None
    return candidate


@lru_cache(maxsize=1)
def load_mdi_manifest() -> MdiManifest:
    """Return the shipped icon manifest, reading it on first use only.

    Cached for the process lifetime: the data is immutable (generated, committed
    and never written at runtime), so one read serves every request. There is no
    I/O at import time.

    :raises MdiManifestError: if the shipped data is missing or malformed.
    """
    directory = resources.files("chime_deck.icons").joinpath(_DATA_ANCHOR, MDI_DATA_DIRECTORY)
    index = _read_object(directory, MANIFEST_INDEX_FILENAME)

    version = index.get("version")
    if not isinstance(version, str) or not version.strip():
        raise MdiManifestError(f"{_display(MANIFEST_INDEX_FILENAME)} has no version string")
    icon_count = index.get("icon_count")
    if not isinstance(icon_count, int) or isinstance(icon_count, bool) or icon_count < 0:
        raise MdiManifestError(f"{_display(MANIFEST_INDEX_FILENAME)} has no icon_count integer")
    shards = index.get("shards")
    if not isinstance(shards, list) or not all(isinstance(shard, str) for shard in shards):
        raise MdiManifestError(f"{_display(MANIFEST_INDEX_FILENAME)} has no shard name list")

    icons: dict[str, str] = {}
    for shard in cast("list[str]", shards):
        if not shard or shard in {".", ".."} or any(s in shard for s in _SHARD_SEPARATORS):
            # Shipped data, so this can only be a bug — but a shard name is a
            # path fragment and the loader must never read outside its directory.
            raise MdiManifestError(
                f"{_display(MANIFEST_INDEX_FILENAME)} names a bad shard {shard!r}"
            )
        for name, path in _read_object(directory, shard).items():
            if MDI_NAME_PATTERN.fullmatch(name) is None:
                raise MdiManifestError(f"{_display(shard)} has the icon name {name!r}")
            if not isinstance(path, str) or not path:
                raise MdiManifestError(f"{_display(shard)} has no path data for the icon {name!r}")
            if name in icons:
                raise MdiManifestError(f"the icon {name!r} is shipped more than once")
            icons[name] = path

    if len(icons) != icon_count:
        raise MdiManifestError(
            f"{_display(MANIFEST_INDEX_FILENAME)} promises {icon_count} icons but the shards "
            f"hold {len(icons)}"
        )
    return MdiManifest(version=version, icons=MappingProxyType(icons))


def icon_path(name: str) -> str | None:
    """Return the shipped path data for *name*, or ``None`` when it is not shipped.

    Total by design: an unknown name is an ordinary answer (a stale ``mdi:``
    reference from a newer icon set renders the fallback icon), not an error.

    :param name: what a client sent, either ``door`` or ``mdi:door``.
    """
    normalised = normalise_icon_name(name)
    if normalised is None:
        return None
    return load_mdi_manifest().icons.get(normalised)


def _read_object(directory: Traversable, filename: str) -> Mapping[str, object]:
    """Read one manifest file and return its JSON object, or raise.

    :param directory: the manifest directory inside the installed package.
    :param filename: file name to read, from the shipped index or a constant.
    :raises MdiManifestError: if the file is unreadable, not JSON, or not an object.
    """
    try:
        text = directory.joinpath(filename).read_text(encoding="utf-8")
    except (OSError, ValueError) as exc:
        raise MdiManifestError(f"{_display(filename)} could not be read: {exc}") from exc
    try:
        value: object = json.loads(text)
    except json.JSONDecodeError as exc:
        raise MdiManifestError(f"{_display(filename)} is not valid JSON: {exc}") from exc
    if not isinstance(value, dict):
        raise MdiManifestError(f"{_display(filename)} is not a JSON object")
    return cast("dict[str, object]", value)


def _display(filename: str) -> str:
    """Return *filename* as a package-relative label for an error message.

    :param filename: file name inside ``data/mdi/``.
    """
    return f"{_DATA_ANCHOR}/{MDI_DATA_DIRECTORY}/{filename}"
