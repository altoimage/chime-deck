"""The MQTT bridge: the connection behind Home Assistant's chime buttons.

Import the public API from this package rather than from the individual
modules: the module layout is an implementation detail. ``MqttBridge`` owns one
``paho-mqtt`` 2.x connection (``CallbackAPIVersion.VERSION2``) — the client id,
the credentials, the last will, the retained availability topic, the Home
Assistant status subscription, the health status and the reconnect.
``MqttDiscovery`` owns what is published over that connection: the discovery
payloads and their lifecycle, and the command-topic press routing. The
``Mqtt*`` error classes are what their validation raises.

Owning ticket: HSD-kslf; the discovery service was added by HSD-c3si.
"""

